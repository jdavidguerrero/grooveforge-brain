const size_t param_count = sizeof(params) / sizeof(params[0]);
bool get_param(const Patch& p, const char* id, float& value) {
    if (!id) return false;
    for (const auto& q : params) if (!std::strcmp(q.id, id)) {
        value = q.enable_bit < 0 ? p.vced[q.offset] : (p.enabled >> q.enable_bit) & 1;
        return true;
    }
    return false;
}
bool set_param(Patch& p, const char* id, float value) {
    if (!id || !std::isfinite(value)) return false;
    for (const auto& q : params) if (!std::strcmp(q.id, id)) {
        const auto v = uint8_t(std::lround(std::clamp(value, float(q.minimum), float(q.maximum))));
        if (q.enable_bit < 0) p.vced[q.offset] = v;
        else p.enabled = (p.enabled & ~(1 << q.enable_bit)) | (v << q.enable_bit);
        return true;
    }
    return false;
}
